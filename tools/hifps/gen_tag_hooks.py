#!/usr/bin/env python3
"""Generate an N64Recomp config with hifps "tag hooks" around the game's 2D draw functions.

Optional, for explicit per-object interpolation ids (see APP.md, "High fps"). The regular build does not need it:
RT64 matches 2D draws across frames on its own. With the hooks, every hooked function calls
mtc_hifps_fn_enter(rdram, func, a0, ra) on entry and mtc_hifps_fn_exit(rdram, func) before each `jr $ra`, and the
display list commands it wrote in between get the id (func, a0 object pointer, caller) in RT64.

Draw functions are found in the splat disassembly (read only) by the GBI command words they build:
  0xB4000000 (texture rectangle second word), 0xC1000017 (S2DEX OBJ_LOADTXTR), 0x04000000 (S2DEX OBJ_SPRITE).

Usage: tools/hifps/gen_tag_hooks.py <disasm/asm/main.s> <base mtc.us.toml> <out.toml> <out RecompiledFuncs dir>
Then: N64Recomp <out.toml>, and configure a build with -DMTC_RECOMPILED_DIR=<out dir>.
The generated config and code are ROM-derived: keep them local (never commit or publish).
"""
import os
import re
import sys

COMMAND_WORDS = ("0xB4000000", "0xC1000017", "0x4000000")
BRANCH = re.compile(r"\b(b|beq|bne|beqz|bnez|blez|bgtz|bltz|bgez|beql|bnel|blezl|bgtzl|bltzl|bgezl|j|jal|jr|jalr|bc1t|bc1f|bc1tl|bc1fl)\b")


def parse(asm_path):
    funcs = []
    cur = None
    for line in open(asm_path, encoding="utf-8", errors="replace"):
        m = re.match(r"^glabel (\S+)", line)
        if m:
            # Only game functions (func_XXXXXXXX) are hooked; named library functions just end the previous one.
            fm = re.fullmatch(r"func_([0-9A-F]{8})", m.group(1))
            cur = {"name": m.group(1), "vram": int(fm.group(1), 16), "insns": []} if fm else None
            if cur:
                funcs.append(cur)
            continue
        if line.startswith("endlabel "):
            cur = None
            continue
        if cur is None:
            continue
        m = re.match(r"^\s*/\* [0-9A-F]+ ([0-9A-F]{8}) [0-9A-F]{8} \*/\s+(\S+)\s*(.*)$", line)
        if m:
            cur["insns"].append((int(m.group(1), 16), m.group(2), m.group(3)))
    return funcs


def main():
    asm_path, base_toml, out_toml, out_dir = sys.argv[1:5]
    funcs = parse(asm_path)
    hooks = []
    hooked = []
    for f in funcs:
        if not any(op == "lui" and any(f"({w} >> 16)" in args for w in COMMAND_WORDS) for _, op, args in f["insns"]):
            continue
        returns = []
        for i, (vram, op, args) in enumerate(f["insns"]):
            if op == "jr" and args.strip() == "$ra":
                prev = f["insns"][i - 1][1] if i > 0 else ""
                if BRANCH.fullmatch(prev):
                    returns = None  # jr $ra in a delay slot: cannot hook its return safely
                    break
                returns.append(vram)
        if not returns:
            continue
        name, fn = f["name"], f"0x{f['vram']:08X}u"
        hooks.append(f'[[patches.hook]]\nfunc = "{name}"\ntext = "extern void mtc_hifps_fn_enter(uint8_t*, uint32_t, uint32_t, uint32_t); '
                     f'mtc_hifps_fn_enter(rdram, {fn}, (uint32_t)ctx->r4, (uint32_t)ctx->r31);"\n')
        for r in returns:
            hooks.append(f'[[patches.hook]]\nfunc = "{name}"\nbefore_vram = 0x{r:08X}\n'
                         f'text = "extern void mtc_hifps_fn_exit(uint8_t*, uint32_t); mtc_hifps_fn_exit(rdram, {fn});"\n')
        hooked.append(name)

    base_dir = os.path.dirname(os.path.abspath(base_toml))
    text = open(base_toml, encoding="utf-8").read()

    def absolutize(m):
        return f'{m.group(1)} = "{os.path.normpath(os.path.join(base_dir, m.group(2)))}"'

    text = re.sub(r'^(elf_path) = "([^"]+)"', absolutize, text, flags=re.M)
    text = re.sub(r'^output_func_path = "[^"]+"', f'output_func_path = "{os.path.abspath(out_dir)}"', text, flags=re.M)
    os.makedirs(os.path.dirname(os.path.abspath(out_toml)), exist_ok=True)
    with open(out_toml, "w", encoding="utf-8") as out:
        out.write(text.rstrip() + "\n\n# ---- hifps tag hooks (generated by tools/hifps/gen_tag_hooks.py) ----\n")
        out.write("\n".join(hooks))
    print(f"{len(hooked)} draw functions hooked ({len(hooks)} hooks) -> {out_toml}")


if __name__ == "__main__":
    main()
